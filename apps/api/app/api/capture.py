"""Token-authenticated patient capture endpoints (/api/capture/{token}).

No clinician login required; access is gated by a short-lived HS256 capture token
generated by the clinician.
"""

from datetime import date
import uuid

from fastapi import (
    APIRouter,
    Depends,
    File,
    Form,
    HTTPException,
    UploadFile,
    status,
)
from fastapi.responses import JSONResponse
import jwt
from sqlalchemy.orm import Session

from app import CLINICAL_DISCLAIMER
from app.api.schemas import CaptureSessionOut, VisitOut
from app.api.visits import get_storage_service, get_youcam_service
from app.auth.jwt import decode_capture_token
from app.config import get_settings
from app.db.models import Clinic, ConcernScore, Patient, Visit
from app.db.session import get_db
from app.domain.concerns import ANALYSIS_VERSION, CONCERN_LIST
from app.services.agent import regenerate_patient_flags
from app.services.storage import PrivateStorageService
from app.services.youcam import (
    YouCamClientProtocol,
    YouCamError,
    YouCamTaskFailedError,
    parse_youcam_raw_result,
)

router = APIRouter(prefix="/capture", tags=["capture"])


def _resolve_patient_from_capture_token(token: str, db: Session) -> Patient:
    try:
        claims = decode_capture_token(token)
        patient_id = uuid.UUID(str(claims["patient_id"]))
    except jwt.ExpiredSignatureError as exc:
        raise HTTPException(
            status_code=status.HTTP_401_UNAUTHORIZED,
            detail="Capture link has expired. Please ask your clinician for a new link.",
        ) from exc
    except (jwt.InvalidTokenError, KeyError, ValueError) as exc:
        raise HTTPException(
            status_code=status.HTTP_401_UNAUTHORIZED,
            detail="Invalid capture link token.",
        ) from exc

    patient = db.get(Patient, patient_id)
    if patient is None:
        raise HTTPException(
            status_code=status.HTTP_404_NOT_FOUND,
            detail="Patient record for this capture link was not found.",
        )
    return patient


@router.get("/{token}", response_model=CaptureSessionOut)
def get_capture_session(
    token: str,
    db: Session = Depends(get_db),
) -> CaptureSessionOut:
    """Validate a patient capture token and return session metadata for the mobile capture UI."""
    patient = _resolve_patient_from_capture_token(token, db)
    clinic = db.get(Clinic, patient.clinic_id)
    clinic_name = clinic.name if clinic else "Bridge Dermatology Clinic"
    first_name = patient.full_name.split()[0] if patient.full_name else "Patient"

    return CaptureSessionOut(
        valid=True,
        patient_id=patient.id,
        patient_display_name=first_name,
        clinic_name=clinic_name,
        consent_version=patient.consent_version,
        privacy_notice="Photos are stored privately and deletable on request.",
        disclaimer=CLINICAL_DISCLAIMER,
    )


@router.post("/{token}/submit", response_model=VisitOut, status_code=status.HTTP_201_CREATED)
async def submit_patient_capture(
    token: str,
    consent_accepted: bool = Form(default=True),
    visit_date: date | None = Form(default=None),
    chief_complaint: str | None = Form(default=None),
    routine_text: str | None = Form(default=None),
    treatment_changes: str | None = Form(default=None),
    image: UploadFile = File(...),
    db: Session = Depends(get_db),
    storage: PrivateStorageService = Depends(get_storage_service),
    youcam: YouCamClientProtocol = Depends(get_youcam_service),
) -> VisitOut | JSONResponse:
    """Accept a guided selfie via a signed patient capture token and run the full visit pipeline."""
    patient = _resolve_patient_from_capture_token(token, db)
    if not consent_accepted:
        raise HTTPException(
            status_code=status.HTTP_400_BAD_REQUEST,
            detail="Patient consent is required before submitting a clinic scan.",
        )

    image_bytes = await image.read()
    if not image_bytes:
        raise HTTPException(
            status_code=status.HTTP_400_BAD_REQUEST,
            detail="Uploaded image file is empty.",
        )

    visit_id = uuid.uuid4()
    filename = image.filename or "selfie.jpg"
    content_type = image.content_type or "image/jpeg"

    image_storage_key = storage.store_visit_selfie(
        patient_id=patient.id,
        visit_id=visit_id,
        image_bytes=image_bytes,
        filename=filename,
    )

    visit = Visit(
        id=visit_id,
        patient_id=patient.id,
        visit_date=visit_date or date.today(),
        chief_complaint=chief_complaint,
        routine_text=routine_text,
        treatment_changes=treatment_changes,
        analysis_version=ANALYSIS_VERSION,
        image_storage_key=image_storage_key,
        youcam_status="pending",
    )
    db.add(visit)
    db.commit()
    db.refresh(visit)

    settings = get_settings()
    try:
        file_id = await youcam.upload_file(
            image_bytes,
            filename=filename,
            content_type=content_type,
        )
        visit.youcam_file_id = file_id

        task_id = await youcam.create_task(
            file_id,
            dst_actions=CONCERN_LIST,
            prerender=True,
        )
        visit.youcam_task_id = task_id
        db.commit()

        raw_result = await youcam.poll_task(task_id)
        parsed_scores = parse_youcam_raw_result(raw_result)

        visit.raw_result = raw_result
        visit.youcam_status = "success"

        for item in parsed_scores:
            mask_storage_key = await storage.cache_concern_mask(
                patient_id=patient.id,
                visit_id=visit.id,
                concern=item.concern,
                mask_url=item.mask_url,
                allow_live_fetch=settings.ALLOW_LIVE_CALLS,
            )
            db.add(
                ConcernScore(
                    visit_id=visit.id,
                    concern=item.concern,
                    score=item.score,
                    severity=item.severity,
                    mask_url=item.mask_url,
                    mask_storage_key=mask_storage_key,
                )
            )

        db.commit()
        regenerate_patient_flags(db, patient.id)
        db.refresh(visit)
        return VisitOut.model_validate(visit)

    except (YouCamTaskFailedError, YouCamError) as exc:
        visit.youcam_status = "failed"
        if isinstance(exc, YouCamTaskFailedError) and exc.raw_result is not None:
            visit.raw_result = exc.raw_result
        db.commit()
        return JSONResponse(
            status_code=status.HTTP_502_BAD_GATEWAY,
            content={
                "detail": str(exc),
                "visit_id": str(visit.id),
                "youcam_status": "failed",
                "disclaimer": CLINICAL_DISCLAIMER,
            },
        )

